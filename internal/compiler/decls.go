// ---- emission

func (c *Compiler) w(format string, args ...any) {
	fmt.Fprintf(&c.out, format, args...)
}

func (c *Compiler) lineDirective(f *File, line int) {
	c.w("//line %s:%d\n", f.Name, line)
}

func (c *Compiler) emitProgram() {
	c.w("// Code generated by rugaroo from %s. DO NOT EDIT.\n\npackage main\n\n", c.mainFile.Name)
	// Order matters for `//line` readability only; Go doesn't care. The
	// translator goes first, so no Ruby file's directive covers it.
	c.w("%s\n\n", strings.TrimSpace(rxTranslateGo()))
	intEqGo := true
	if eq := c.classes["Integer"].lookup("=="); eq == nil || eq.M.File == nil || !eq.M.File.isPrelude() {
		intEqGo = false
	}
	for _, v := range c.verbatim {
		c.lineDirective(v.File, v.Line)
		code := v.code
		if !intEqGo {
			code = strings.Replace(code, "const rbIntEqGo = true", "const rbIntEqGo = false", 1) // a program's own Integer#== (decision 387)
		}
		c.w("%s\n\n", strings.TrimSpace(code))
	}
	if slices.ContainsFunc(c.classList, func(cls *Class) bool { return cls.hashBase && cls.Super.RubyName == "Hash" }) {
		c.w("type %s[V comparable] = Hash[any, V]\n\n", superField(c.classes["Hash"]))
	}
	if c.pruneGems { // stubRejected's stubs raise it, and they are written after the prune (decision 324)
		c.w("var _ = NewNotImplementedError\n\n")
	}
	based := map[*Class]bool{}
	for _, cls := range c.classList {
		if sup := cls.Super; cls.hashBase && sup.RubyName != "Hash" && !based[sup] {
			based[sup] = true
			if tps := strings.Join(sup.TypeParams, ", "); tps != "" {
				c.w("type %s[%s comparable] = %s[%s]\n\n", superField(sup), tps, sup.Name, tps)
			} else {
				c.w("type %s = %s\n\n", superField(sup), sup.Name)
			}
		}
	}
	classes := c.sortedClasses()
	for _, cls := range classes {
		c.emitClassType(cls)
	}
	for _, cls := range classes {
		if cls.isTemplate() {
			continue
		}
		for _, m := range cls.MethodList {
			c.emitMethod(m)
		}
	}
	for _, m := range c.topDefList {
		c.emitTopDef(m)
	}
	for _, k := range c.constList {
		c.emitConst(k)
	}
	if len(c.evalClasses) > 0 { // a constant a run-time eval defines is missing until then: MRI calls the module's const_missing (decision 324)
		c.noteDyn("const_missing")
		c.w("var _ = func() bool {\n\trbConstMissingHook = func(m rbModule, name string) (any, bool) {\n")
		c.w("\t\tif r, ok := m.(interface{ DynConstMissing(...any) any }); ok {\n\t\t\treturn r.DynConstMissing(Symbol(name)), true\n\t\t}\n")
		c.w("\t\treturn nil, false\n\t}\n\treturn true\n}()\n\n")
	}

	c.emitMain()
	c.noteUserToJson()
}

// emitNext is one batch of the rest of the program, given what the pruned program so far reaches: forwarders of reached classes and dispatchers of reached names, until a round adds nothing; then the tables every body has contributed to by now, once; then nil. The tables open paths to more code, so rounds go on after them; a late body that adds to a table's inputs (a tuple type, a literal) is errPruneIncomplete, and the caller recompiles with everything eager.
func (c *Compiler) emitNext(reached, selected func(string) bool, kept keptCode) ([]byte, error) {
	c.out.Reset()
	c.keptView = kept
	for _, cls := range c.sortedClasses() {
		if !c.fwdOut[cls] && (c.dynEvery || reached(cls.Name)) {
			c.fwdOut[cls] = true
			c.emitForwarders(cls)
		}
	}
	c.emitDynamic(reached, selected)
	c.emitSends(reached)
	c.emitUnions(reached) // a helper is a function like any other: emitted once kept code names it (decision 432)
	marshal := reached("rbMDumpGen") || reached("rbMLoadGen")
	// Marshal's cases were rendered with the tables: a later value type, or a class they skipped and something now reaches, needs them redone
	stale := marshal && len(c.marshalSeen) != c.marshalAt || slices.ContainsFunc(c.marshalSkipped, reached)
	if c.procsOut && len(c.keptProcs())+len(c.keptStrLits()) != c.procsAt { // what the late tables reached adds to them
		return nil, errPruneIncomplete
	}
	if c.tablesOut && (c.tableInputs() != c.tablesAt || stale) {
		return nil, errPruneIncomplete
	}
	if c.out.Len() == 0 {
		switch {
		case !c.tablesOut:
			c.tablesOut = true
			c.prepareMarshal() // first: its types note boxes and tuples the tables list
			c.tablesAt = c.tableInputs()
			c.emitTables()
		case marshal && !c.marshalOut: // Marshal may be reached only through the tables (minitest's _Call)
			if c.marshalErr != nil {
				panic(*c.marshalErr)
			}
			c.marshalOut = true
			c.w("%s", c.marshalCode)
		case c.marshalOut && !c.marshalLate: // last: its cases are only the classes reached by then
			c.marshalLate = true
			c.emitMarshalClasses(reached)
		case !c.procsOut: // after everything else: its cases are the Proc types kept code makes (decision 431)
			c.procsOut = true
			c.emitProcTables()
			c.emitStringLits()
			c.procsAt = len(c.keptProcs()) + len(c.keptStrLits())
		default:
			return nil, nil
		}
	}
	return []byte(c.out.String()), nil
}

// tableInputs is what emitTables reads, as sizes and flags: the maps only grow, so equal sizes mean equal contents.
type tableInputs struct {
	argBoxes, boxes, procTypes, pkgVars, strLits, optConv      int // procTypes only triggers the eager recompile now: the proc tables go out last (decision 431)
	classOf, dynEvery, respondEvery, callable, dynEach, reqTab bool
}

func (c *Compiler) tableInputs() tableInputs {
	return tableInputs{
		argBoxes: len(c.argBoxes), boxes: len(c.boxes), procTypes: len(c.procTypes),
		pkgVars: len(c.pkgVars), strLits: len(c.strLits), optConv: len(c.optConv),
		classOf: c.classOf, dynEvery: c.dynEvery, respondEvery: c.respondEvery, callable: c.callable != nil,
		dynEach: c.dynEach, reqTab: c.needRequireTable,
	}
}

// emitOptClassFrom emits rbOptClassFrom(zero, v): rbConv's box of an untyped value into a class's T? where a generic
// body has only the type parameter (Homebrew's `set_unique_stanza[U]` returning an ivar as Version?): nil, or the
// object behind a new pointer. One case per class T? some call binds a type parameter to.
func (c *Compiler) emitOptClassFrom() {
	c.w("func rbOptClassFrom(zero any, v any) (any, bool) {\n\tswitch zero.(type) {\n")
	for _, g := range slices.Sorted(maps.Keys(c.optConv)) {
		if strings.HasPrefix(g, "*") { // a leaf's C? is its *C (decision 360): the object itself
			c.w("\tcase %s:\n\t\tif v == nil {\n\t\t\treturn (%s)(nil), true\n\t\t}\n\t\tif x, ok := v.(%s); ok {\n\t\t\treturn x, true\n\t\t}\n", g, g, g)
			continue
		}
		c.w("\tcase *%s:\n\t\tif v == nil {\n\t\t\treturn (*%s)(nil), true\n\t\t}\n\t\tif x, ok := v.(%s); ok {\n\t\t\treturn &x, true\n\t\t}\n", g, g, g)
	}
	c.w("\tdefault: // gocritic rejects the one-case switch pruning can leave\n\t}\n\treturn nil, false\n}\n\n")
}

// emitTables: what every emitted body has contributed to.
func (c *Compiler) emitTables() {
	if c.usesLineNo { // $. is read: gets stores the line number for it (decision 425)
		c.w("func init() { rbTrackLineNo = true }\n\n")
	}
	if c.dynEvery || c.respondEvery {
		c.emitNameSwitches()
	}
	if c.dynEvery || c.callable != nil {
		c.emitCallTables()
	}
	c.emitSendOn()
	c.emitAliasKeys()
	c.emitClassOf()
	c.emitModIsA()
	c.emitFrozenFlag()
	c.emitDynEach()
	c.emitLoadedFeatures()
	c.emitSplatObj()
	c.emitDelegateObj()
	c.emitOptClassFrom()
	c.emitTuples()
	c.emitBoxes()
	c.emitClassMeta()
	// last: every body, main included, has registered its literals by now
	if c.needRequireTable {
		c.emitRequireTable()
	}
	c.w("%s\n\n", strings.TrimSpace(rxAltGo()))             // kept when a pattern or a body names rxAltReady (decisions 242, 432)
	for _, r := range slices.Sorted(maps.Keys(c.pkgVars)) { // named by what they are, so sorted they do not depend on render order
		c.w("%s\n\n", r)
	}
}

// noteUserToJson: the json generator calls to_json(state) on what it
// renders, which reaches a user to_json declared other than
// (*untyped) -> String only through its Dyn wrapper (docs/design.md decision 25).
func (c *Compiler) noteUserToJson() {
	for _, cls := range c.classList {
		m := cls.Methods["to_json"]
		if m == nil || m.File.isPrelude() {
			continue
		}
		if len(m.Params) != 1 || !m.Params[0].Rest || !isAny(m.Params[0].Type) || !isClass(m.Ret, "String") {
			c.noteDyn("to_json")
			return
		}
	}
}

// keptStrLits is rbStringLits' entries: the Ruby literal texts a kept Go literal spells, the only bytes the linker can share with a String (decision 432).
func (c *Compiler) keptStrLits() []string {
	var out []string
	for _, s := range slices.Sorted(maps.Keys(c.strLits)) {
		if c.keptView == nil || c.keptView.keptString(s) {
			out = append(out, s)
		}
	}
	return out
}

// emitStringLits: each entry aliases every literal of its text in the program (rbStrFrozen); emitted with the proc tables, once kept code stopped growing.
func (c *Compiler) emitStringLits() {
	c.w("var rbStringLits = [...]string{\n")
	for _, s := range c.keptStrLits() {
		c.w("\t%s,\n", strconv.Quote(s))
	}
	c.w("}\n\n")
}

// emitLoadedFeatures emits rbLoadedFeatures, gem code's `$LOADED_FEATURES` (decision 444): the source files compiled
// into the program, in load order, a new Array per read. The pruner drops it when nothing reads the global.
func (c *Compiler) emitLoadedFeatures() {
	var elems []string
	for _, f := range c.files {
		if !f.isPrelude() && f.path != "" && !f.synth {
			elems = append(elems, strconv.Quote(f.path))
		}
	}
	c.w("func rbLoadedFeatures() *Array[String] {\n\treturn %s\n}\n\n", arrayLit("String", elems))
}

// emitSplatObj emits rbSplatObj, `*x` of an untyped x (decision 444): a gem or user object with its own to_a spreads
// what it answers (parser's `name, = *node`: AST::Node#to_a is its children), one case per Go shape of such a to_a;
// anything else is rbSplatAny's (an Array's elements, a Hash's pairs, nothing for nil, else x itself).
func (c *Compiler) emitSplatObj() {
	c.w("func rbSplatObj(x any) []any {\n\tswitch r := x.(type) {\n")
	seen := map[string]bool{}
	for _, cls := range c.classList {
		m := cls.Methods["to_a"]
		if m == nil || m.File == nil || m.File.isPrelude() || len(m.Params) > 0 || m.Block != nil || m.generic() || len(cls.TypeParams) > 0 || cls.metaOf != nil || cls.hashBase || !cls.isStruct() {
			continue
		}
		params, ret := c.sig(m, nil)
		shape := "interface{ " + m.GoName + "(" + params + ") " + ret + " }"
		if seen[shape] || !strings.HasPrefix(ret, "*Array[") && ret != "any" {
			continue
		}
		seen[shape] = true
		c.w("\tcase %s:\n\t\treturn rbSplatAny(any(r.%s()))\n", shape, m.GoName)
	}
	c.w("\t}\n\treturn rbSplatAny(x)\n}\n\n")
}
